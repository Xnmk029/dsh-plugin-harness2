"""Improver channels. Only `dsh` exists; `claude_cli` is deliberately NOT implemented."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from . import dsh_cli
from .dsh_cli import LiveNotEnabled, RunPlan

# Improver sessions never get the web: tool-web disabled, same as rollouts.
IMPROVER_PATCH = "# Generated by harness2_dsh improver channel `dsh`.\n- id: tool-web\n  disabled: true\n"


@dataclass(frozen=True)
class ImproverResult:
    plan: RunPlan
    live: bool
    stdout: str = ""


class DshChannel:
    """Runs one improver session with cwd = the context dir. Dry-run unless HARNESS2_DSH_LIVE=1."""

    name = "dsh"

    def __init__(self, *, profile: str = "headless", home_base: Path | None = None, dry_run: bool | None = None) -> None:
        """`dry_run=True` forces a dry run even with HARNESS2_DSH_LIVE=1; None defers to the env gate."""
        self.profile = profile
        self.dry_run = dry_run
        self.home_base = Path(home_base) if home_base else None

    def run(self, prompt: str, context_dir: Path, *, run_id: str | None = None, timeout: float | None = 1800) -> ImproverResult:
        context_dir = Path(context_dir).resolve()
        if not context_dir.is_dir():
            raise FileNotFoundError(f"context_dir {context_dir} does not exist")
        run_id = run_id or dsh_cli.new_run_id("improver")
        live = dsh_cli.live_enabled() and not self.dry_run
        base = self.home_base or dsh_cli.home_base()
        # The patch lives beside the home, never inside the context dir the improver can read.
        patch = base / run_id / "improver.patch.yml"
        plan = dsh_cli.build_plan(
            run_id=run_id,
            profile=self.profile,
            task=prompt,
            cwd=context_dir,
            patch_path=patch,
            base=base,
            dry_run=not live,
            install_plugin=False,
        )
        if not live:
            return ImproverResult(plan=plan, live=False)
        patch.parent.mkdir(parents=True, exist_ok=True)
        patch.write_text(IMPROVER_PATCH, encoding="utf-8")
        proc = dsh_cli.run_plan(plan, timeout=timeout)
        if proc.returncode != 0:
            raise RuntimeError(f"improver dsh exited {proc.returncode}: {proc.stderr.strip()[-500:]}")
        return ImproverResult(plan=plan, live=True, stdout=proc.stdout)


CHANNELS = {"dsh": DshChannel}


def make_channel(name: str, **kwargs) -> DshChannel:
    if name == "claude_cli":
        raise ValueError("improver channel 'claude_cli' is intentionally not implemented in harness2_dsh")
    if name not in CHANNELS:
        raise ValueError(f"unknown improver channel {name!r}; available: {sorted(CHANNELS)}")
    return CHANNELS[name](**kwargs)


__all__ = ["CHANNELS", "DshChannel", "ImproverResult", "LiveNotEnabled", "make_channel"]
