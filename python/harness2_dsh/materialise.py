"""Install mode `dsh_workspace`: copy the editable tree into a workspace and generate the patch.

Tree layout (the dsh surface, a subset of Harness² c1..c8):

  c1 systemprompt.md            -> sections.systemPromptFile
  c2 guardrails.md              -> sections.guardrailsFile
  c3 LongTermMEMORY.md          -> sections.memoryFile
  c4 tool_descriptions/tool_guidance.md -> sections.toolGuidanceFile
  c6 .agents/skills/<n>/SKILL.md   copied (dsh-skill-filesystem root is the workspace)
  c7 scripts/                      copied (run through the bash tool)
  c8 .codex/hooks.json             copied; wired only with enable_hooks=True
  c5 sub_agents/                   NOT supported in this MVP (reported in Install.skipped)

Only data varies per candidate; the plugin code is fixed (packages/dsh-plugin-harness2).
"""

from __future__ import annotations

import hashlib
import json
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Sequence

INSTALL_MODE = "dsh_workspace"
RECORDER_DIR = ".harness2"  # under work_dir; hidden from the agent by the default deny glob
PATCH_NAME = "candidate.patch.yml"

# (tree-relative file, plugin config key under `sections`)
SECTION_FILES: tuple[tuple[str, str], ...] = (
    ("systemprompt.md", "systemPromptFile"),
    ("guardrails.md", "guardrailsFile"),
    ("LongTermMEMORY.md", "memoryFile"),
    ("tool_descriptions/tool_guidance.md", "toolGuidanceFile"),
)
COPY_DIRS = (".agents", "scripts", ".codex", "tool_descriptions")
HOOK_EVENTS = ("SessionStart", "UserPromptSubmit", "PreToolUse", "PostToolUse", "Stop")
DEFAULT_DENY_PATH_GLOBS = ("**/.harness2/**",)
WEB_TOOLS = ("web_search", "web_fetch")
PATH_ARG_KEYS = ("file_path", "path", "paths", "filePath")
MAX_CHARS = 16384
_IGNORED = shutil.ignore_patterns("__pycache__", "*.pyc", ".git", "node_modules", ".venv")


@dataclass(frozen=True)
class Install:
    """A materialised workspace ready for one dsh process."""

    work_dir: Path
    patch_path: Path
    recorder_path: Path
    recorder_text_path: Path
    fingerprint: str  # digest of the SOURCE tree
    files: tuple[str, ...] = ()  # work_dir-relative files copied
    skipped: tuple[str, ...] = ()
    extras: dict = field(default_factory=dict)


def tree_fingerprint(tree_dir: Path) -> str:
    h = hashlib.sha256()
    for p in sorted(x for x in tree_dir.rglob("*") if x.is_file()):
        rel = p.relative_to(tree_dir)
        if any(part in {"__pycache__", ".git", "node_modules", ".venv"} for part in rel.parts):
            continue
        h.update(rel.as_posix().encode() + b"\0" + p.read_bytes() + b"\0")
    return h.hexdigest()[:16]


def _q(value: str) -> str:
    """YAML scalar: a JSON string is a valid double-quoted YAML scalar."""
    return json.dumps(value)


def _flow(items: Sequence[str]) -> str:
    return "[" + ", ".join(_q(i) for i in items) + "]"


def hooks_nonempty(hooks_json: Path) -> bool:
    try:
        data = json.loads(hooks_json.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return False
    hooks = data.get("hooks", {}) if isinstance(data, dict) else {}
    return any(hooks.get(ev) for ev in HOOK_EVENTS)


def render_patch(
    *,
    section_paths: dict[str, Path],
    recorder_path: Path,
    recorder_text_path: Path,
    deny_tools: Sequence[str] = WEB_TOOLS,
    deny_path_globs: Sequence[str] = DEFAULT_DENY_PATH_GLOBS,
    disable_web: bool = True,
    hooks_config: Path | None = None,
) -> str:
    """The candidate patch: replaces the bundle's `harness2` row (by id) with this candidate's paths.

    A replace restates the whole config (see the plugin README), so every field is written.
    Paths are absolute: the plugin rejects relative section paths and dsh resolves relative
    hooks paths from the launching directory.
    """
    lines = [
        "# Generated by harness2_dsh (install mode dsh_workspace). One copy per candidate/rollout.",
        "# Replaces the bundle row `harness2` (dsh-plugin-harness2); all paths are absolute.",
    ]
    if disable_web:
        lines += ["- id: tool-web", "  disabled: true", ""]
    lines += ["- id: harness2", "  config:", "    sections:"]
    for _, key in SECTION_FILES:
        lines.append(f"      {key}: {_q(str(section_paths[key])) if key in section_paths else _q('')}")
    lines += [
        "    recorder:",
        f"      path: {_q(str(recorder_path))}",
        "      text: true",
        f"      textPath: {_q(str(recorder_text_path))}",
        f"      maxChars: {MAX_CHARS}",
        "    guard:",
        f"      denyTools: {_flow(deny_tools)}",
        f"      denyPathGlobs: {_flow(deny_path_globs)}",
        f"      pathArgKeys: {_flow(PATH_ARG_KEYS)}",
    ]
    if hooks_config is not None:
        lines += [
            "",
            "# Needs `@deepseek-ai/dsh-hooks-codex` installed in the profile (experimental).",
            "- insert:",
            "    - id: harness2-hooks-codex",
            "      name: '@deepseek-ai/dsh-hooks-codex'",
            "      config:",
            f"        configPath: {_q(str(hooks_config))}",
        ]
    return "\n".join(lines) + "\n"


def materialise_dsh_workspace(
    tree_dir: Path,
    work_dir: Path,
    *,
    enable_hooks: bool = False,
    deny_tools: Sequence[str] | None = None,
    deny_path_globs: Sequence[str] | None = None,
    disable_web: bool = True,
) -> Install:
    """Copy `tree_dir` into `work_dir` and write `<work_dir>/candidate.patch.yml`.

    `work_dir` must be empty or absent so a stale rollout can never leak into a candidate.
    """
    tree_dir, work_dir = Path(tree_dir).resolve(), Path(work_dir).resolve()
    if not (tree_dir / "systemprompt.md").is_file():
        raise ValueError(f"{tree_dir} is not a dsh harness tree (no systemprompt.md)")
    if work_dir.exists() and any(work_dir.iterdir()):
        raise FileExistsError(f"work_dir {work_dir} is not empty")
    work_dir.mkdir(parents=True, exist_ok=True)

    files: list[str] = []
    for rel, _ in SECTION_FILES:
        src = tree_dir / rel
        if src.is_file():
            dst = work_dir / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
            files.append(rel)
    for d in COPY_DIRS:
        src = tree_dir / d
        if src.is_dir():
            shutil.copytree(src, work_dir / d, dirs_exist_ok=True, ignore=_IGNORED)
    for p in sorted(work_dir.rglob("*")):
        rel = p.relative_to(work_dir).as_posix()
        if p.is_file() and rel not in files:
            files.append(rel)

    skipped = tuple(n for n in ("sub_agents", "AGENTS.md") if (tree_dir / n).exists())
    section_paths = {key: work_dir / rel for rel, key in SECTION_FILES if (work_dir / rel).is_file()}
    rec_dir = work_dir / RECORDER_DIR
    recorder, recorder_txt = rec_dir / "trajectory.jsonl", rec_dir / "trajectory.jsonl.txt"
    hooks = work_dir / ".codex" / "hooks.json"
    hooks_cfg = hooks if enable_hooks and hooks_nonempty(hooks) else None

    patch_path = work_dir / PATCH_NAME
    patch_path.write_text(
        render_patch(
            section_paths=section_paths,
            recorder_path=recorder,
            recorder_text_path=recorder_txt,
            deny_tools=WEB_TOOLS if deny_tools is None else deny_tools,
            deny_path_globs=DEFAULT_DENY_PATH_GLOBS if deny_path_globs is None else deny_path_globs,
            disable_web=disable_web,
            hooks_config=hooks_cfg,
        ),
        encoding="utf-8",
    )
    return Install(
        work_dir=work_dir,
        patch_path=patch_path,
        recorder_path=recorder,
        recorder_text_path=recorder_txt,
        fingerprint=tree_fingerprint(tree_dir),
        files=tuple(sorted(files)),
        skipped=skipped,
        extras={"install_mode": INSTALL_MODE, "hooks_wired": str(hooks_cfg is not None).lower()},
    )
